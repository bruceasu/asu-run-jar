package build

import (
	"bufio"
	"bytes"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

// EnsureGitSetup initializes git repository and creates .gitignore
func EnsureGitSetup(baseDir string) error {
	if _, err := os.Stat(baseDir); err != nil {
		return fmt.Errorf("skip git setup, directory missing: %w", err)
	}
	if err := ensureGitIgnore(baseDir); err != nil {
		return err
	}
	if _, err := exec.LookPath("git"); err != nil {
		return nil
	}
	if isInsideGitWorkTree(baseDir) {
		if err := gitAddPath(baseDir); err != nil {
			return err
		}
		return nil
	}
	if _, err := os.Stat(filepath.Join(baseDir, ".git")); err == nil {
		return nil
	}
	out, errb, err := RunCommandDir(baseDir, "git", "init")
	if err != nil {
		return fmt.Errorf("git init failed: %v\n%s\n%s", err, out, errb)
	}
	Info("[GIT] Initialized git repository in %s", baseDir)
	return nil
}

func isInsideGitWorkTree(path string) bool {
	out, _, err := RunCommandDir(path, "git", "rev-parse", "--is-inside-work-tree")
	if err != nil {
		return false
	}
	return strings.TrimSpace(out) == "true"
}

func gitTopLevel(path string) (string, error) {
	out, errb, err := RunCommandDir(path, "git", "rev-parse", "--show-toplevel")
	if err != nil {
		return "", fmt.Errorf("git rev-parse failed: %v\n%s\n%s", err, out, errb)
	}
	return strings.TrimSpace(out), nil
}

func gitAddPath(path string) error {
	root, err := gitTopLevel(path)
	if err != nil {
		return err
	}
	rel, err := filepath.Rel(root, path)
	if err != nil {
		return err
	}
	if rel == "." {
		return nil
	}
	out, errb, err := RunCommandDir(root, "git", "add", rel)
	if err != nil {
		return fmt.Errorf("git add failed: %v\n%s\n%s", err, out, errb)
	}
	Info("[GIT] Added %s to repository", rel)
	return nil
}

func ensureGitIgnore(baseDir string) error {
	path := filepath.Join(baseDir, ".gitignore")
	entries := []string{
		"target/",
		"bin/",
		"classes/",
		"build/",
		"out/",
		"lib/",
		"*.class",
		"*.jar",
		"*.war",
		"*.ear",
		"*.iml",
		"*.ipr",
		"*.iws",
		"*.log",
		"*.tmp",
		"*.bak",
		"*.swp",
		".classpath",
		".project",
		".settings/",
		".idea/",
		".vscode/",
		".DS_Store",
		"node_modules/",
	}

	exists := true
	data, err := os.ReadFile(path)
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			exists = false
		} else {
			return fmt.Errorf("read .gitignore: %w", err)
		}
	}

	if !exists {
		var builder strings.Builder
		builder.WriteString("# Java project ignores generated by ajava\n")
		for _, e := range entries {
			builder.WriteString(e)
			builder.WriteString("\n")
		}
		if err := os.WriteFile(path, []byte(builder.String()), 0644); err != nil {
			return fmt.Errorf("write .gitignore: %w", err)
		}
		Info("[GIT] Created .gitignore in %s", baseDir)
		return nil
	}

	existing := make(map[string]struct{})
	scanner := bufio.NewScanner(bytes.NewReader(data))
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		existing[line] = struct{}{}
	}
	if err := scanner.Err(); err != nil {
		return fmt.Errorf("scan .gitignore: %w", err)
	}

	var missing []string
	for _, e := range entries {
		if _, ok := existing[e]; !ok {
			missing = append(missing, e)
		}
	}
	if len(missing) == 0 {
		return nil
	}

	f, err := os.OpenFile(path, os.O_APPEND|os.O_WRONLY, 0644)
	if err != nil {
		return fmt.Errorf("open .gitignore for append: %w", err)
	}
	defer f.Close()

	if len(data) > 0 && data[len(data)-1] != '\n' {
		if _, err := f.WriteString("\n"); err != nil {
			return fmt.Errorf("write newline to .gitignore: %w", err)
		}
	}
	if _, err := f.WriteString("\n# Updated by ajava\n"); err != nil {
		return fmt.Errorf("append header to .gitignore: %w", err)
	}
	for _, e := range missing {
		if _, err := f.WriteString(e + "\n"); err != nil {
			return fmt.Errorf("append entry to .gitignore: %w", err)
		}
	}
	Info("[GIT] Updated .gitignore in %s", baseDir)
	return nil
}
